package DbPeru.Posm.Modelo;

public class Persona {
   private String apelPersona;
   private String creaUsuario;
   private String direPersona;
   private String emailPersona;
   private int estaPersona;
   private String fecCrea;
   private String fecMod;
   private int idPersona;
   private String modUsuario;
   private String nomPersona;
   private String razsPersona;

   public String getApelPersona() {
      return this.apelPersona;
   }

   public void setApelPersona(String apelPersona) {
      this.apelPersona = apelPersona;
   }

   public String getCreaUsuario() {
      return this.creaUsuario;
   }

   public void setCreaUsuario(String creaUsuario) {
      this.creaUsuario = creaUsuario;
   }

   public String getDirePersona() {
      return this.direPersona;
   }

   public void setDirePersona(String direPersona) {
      this.direPersona = direPersona;
   }

   public String getEmailPersona() {
      return this.emailPersona;
   }

   public void setEmailPersona(String emailPersona) {
      this.emailPersona = emailPersona;
   }

   public int getEstaPersona() {
      return this.estaPersona;
   }

   public void setEstaPersona(int estaPersona) {
      this.estaPersona = estaPersona;
   }

   public String getFecCrea() {
      return this.fecCrea;
   }

   public void setFecCrea(String fecCrea) {
      this.fecCrea = fecCrea;
   }

   public String getFecMod() {
      return this.fecMod;
   }

   public void setFecMod(String fecMod) {
      this.fecMod = fecMod;
   }

   public int getIdPersona() {
      return this.idPersona;
   }

   public void setIdPersona(int idPersona) {
      this.idPersona = idPersona;
   }

   public String getModUsuario() {
      return this.modUsuario;
   }

   public void setModUsuario(String modUsuario) {
      this.modUsuario = modUsuario;
   }

   public String getNomPersona() {
      return this.nomPersona;
   }

   public void setNomPersona(String nomPersona) {
      this.nomPersona = nomPersona;
   }

   public String getRazsPersona() {
      return this.razsPersona;
   }

   public void setRazsPersona(String razsPersona) {
      this.razsPersona = razsPersona;
   }
}
