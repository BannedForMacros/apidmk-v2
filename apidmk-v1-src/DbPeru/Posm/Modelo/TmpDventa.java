package DbPeru.Posm.Modelo;

public class TmpDventa {
   private int codpersona;
   private String codtipodoc;
   private String nomcli;
   private String numdocper;
   private String numero;
   private String serie;

   public int getCodpersona() {
      return this.codpersona;
   }

   public void setCodpersona(int codpersona) {
      this.codpersona = codpersona;
   }

   public String getCodtipodoc() {
      return this.codtipodoc;
   }

   public void setCodtipodoc(String codtipodoc) {
      this.codtipodoc = codtipodoc;
   }

   public String getNomcli() {
      return this.nomcli;
   }

   public void setNomcli(String nomcli) {
      this.nomcli = nomcli;
   }

   public String getNumdocper() {
      return this.numdocper;
   }

   public void setNumdocper(String numdocper) {
      this.numdocper = numdocper;
   }

   public String getNumero() {
      return this.numero;
   }

   public void setNumero(String numero) {
      this.numero = numero;
   }

   public String getSerie() {
      return this.serie;
   }

   public void setSerie(String serie) {
      this.serie = serie;
   }
}
