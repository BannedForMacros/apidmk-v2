package DbPeru.Posm.Modelo;

public class Familia {
   public String codFamilia;
   public String descFam;
   public String subfDes;
   public int estaFamilia;

   public String getCodFamilia() {
      return this.codFamilia;
   }

   public void setCodFamilia(String codFamilia) {
      this.codFamilia = codFamilia;
   }

   public String getDescFam() {
      return this.descFam;
   }

   public void setDescFam(String descFam) {
      this.descFam = descFam;
   }

   public String getSubfDes() {
      return this.subfDes;
   }

   public void setSubfDes(String subfDes) {
      this.subfDes = subfDes;
   }

   public int getEstaFamilia() {
      return this.estaFamilia;
   }

   public void setEstaFamilia(int estaFamilia) {
      this.estaFamilia = estaFamilia;
   }
}
