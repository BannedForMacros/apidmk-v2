package DbPeru.Posm.Modelo;

public class Documento {
   private String abreDocumento;
   private String codDocumento;
   private String creaUsuario;
   private String csunDocumento;
   private String descDocumento;
   private int estaDocumento;
   private String fecCrea;
   private String fecMod;
   private String modUsuario;

   public String getAbreDocumento() {
      return this.abreDocumento;
   }

   public void setAbreDocumento(String abreDocumento) {
      this.abreDocumento = abreDocumento;
   }

   public String getCodDocumento() {
      return this.codDocumento;
   }

   public void setCodDocumento(String codDocumento) {
      this.codDocumento = codDocumento;
   }

   public String getCreaUsuario() {
      return this.creaUsuario;
   }

   public void setCreaUsuario(String creaUsuario) {
      this.creaUsuario = creaUsuario;
   }

   public String getCsunDocumento() {
      return this.csunDocumento;
   }

   public void setCsunDocumento(String csunDocumento) {
      this.csunDocumento = csunDocumento;
   }

   public String getDescDocumento() {
      return this.descDocumento;
   }

   public void setDescDocumento(String descDocumento) {
      this.descDocumento = descDocumento;
   }

   public int getEstaDocumento() {
      return this.estaDocumento;
   }

   public void setEstaDocumento(int estaDocumento) {
      this.estaDocumento = estaDocumento;
   }

   public String getFecCrea() {
      return this.fecCrea;
   }

   public void setFecCrea(String fecCrea) {
      this.fecCrea = fecCrea;
   }

   public String getFecMod() {
      return this.fecMod;
   }

   public void setFecMod(String fecMod) {
      this.fecMod = fecMod;
   }

   public String getModUsuario() {
      return this.modUsuario;
   }

   public void setModUsuario(String modUsuario) {
      this.modUsuario = modUsuario;
   }
}
